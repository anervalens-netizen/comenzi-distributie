import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {DatabaseSync} from 'node:sqlite';
import {build} from 'esbuild';
const root=mkdtempSync(join(tmpdir(),'partner-activity-test-'));
try{
 const modulePath=join(root,'snapshot.mjs');
 await build({entryPoints:['lib/partner-activity-snapshot.ts'],outfile:modulePath,bundle:true,platform:'node',format:'esm',logLevel:'silent'});
 const {buildActivitySnapshot,readActivitySnapshot}=await import(pathToFileURL(modulePath).href);
 assert.equal(readActivitySnapshot([],root).state,'unavailable');
 mkdirSync(join(root,'client-history'));
 const history=join(root,'client-history','client-sales-history.sqlite'),app=join(root,'mobiup.sqlite');
 const c=new DatabaseSync(history),a=new DatabaseSync(app);
 a.exec('CREATE TABLE customers(id TEXT PRIMARY KEY,data TEXT)');
 for(const [id,cui] of [['a','123'],['b','123'],['hidden','999']])a.prepare('INSERT INTO customers VALUES(?,?)').run(id,JSON.stringify({cui}));
 a.close();
 c.exec(`
 CREATE TABLE history_meta(key TEXT,value TEXT); INSERT INTO history_meta VALUES('current_reference','ref');
 CREATE TABLE history_imports(id INTEGER,sha256 TEXT,state TEXT,period_start TEXT,period_end TEXT,row_count INTEGER);
 INSERT INTO history_imports VALUES(1,'hash','active','2026-01-01','2026-09-30',10);
 CREATE TABLE history_references(id TEXT,master_json TEXT); INSERT INTO history_references VALUES('ref','[]');
 CREATE TABLE history_identities(id INTEGER,client_code TEXT); INSERT INTO history_identities VALUES(1,'123'),(2,'999');
 CREATE TABLE history_allocations(identity_id INTEGER,reference_id TEXT,status TEXT,partner_ids_json TEXT,candidates_json TEXT);
 INSERT INTO history_allocations VALUES(1,'ref','direct_code','["a","a","b"]','[]'),(2,'ref','single_partner','["hidden"]','[]');
 CREATE TABLE history_rows(import_id INTEGER,identity_id INTEGER,date TEXT,site_id TEXT,document_number TEXT,value_cents INTEGER,quantity_micros INTEGER);
 `);
 const insert=c.prepare('INSERT INTO history_rows VALUES(1,?,?,?,?,?,?)');
 for(const [i,date] of ['2026-06-01','2026-06-08','2026-06-15','2026-06-22','2026-06-29','2026-07-06'].entries())insert.run(1,date,'site',String(i),10000,1000000);
 insert.run(1,'2026-09-29','site','cancel',500,1000000);insert.run(1,'2026-09-29','site','cancel',-500,-1000000);
 insert.run(1,'2026-09-30','site','free',0,1000000);insert.run(2,'2026-09-30','other','buy',70000,1000000);
 c.close();
 const historyBefore=readFileSync(history),appBefore=readFileSync(app);
 const built=buildActivitySnapshot(root,'2026-09-30');assert.equal(built.rows,3);
 const result=readActivitySnapshot([{id:'a',cui:'RO123'},{id:'b',cui:'123'},{id:'unlinked',cui:'123'}],root,'2026-09-30');
 assert.equal(result.state,'ready');assert.equal(result.rows.size,2,'snapshot returns authorized exact IDs only');
 const sales=result.rows.get('a');
 assert.deepEqual(sales.billingYears,['2026']);assert.equal(sales.activity.lastBilling,'2026-07-06');assert.equal(sales.activity.billingDays,6,'duplicate membership never multiplies days');
 assert.equal(sales.activity.status,'inactive');assert.equal(sales.activity.alertEligible,true);
 assert.equal(sales.recentCents,0);assert.equal(result.rows.get('b').activity.billingDays,6);
 assert.equal(readActivitySnapshot([{id:'a',cui:'changed'}],root,'2026-09-30').rows.size,0,'changed company must be reconciled');
 const stale=readActivitySnapshot([{id:'a',cui:'123'}],root,'2026-10-05');assert.equal(stale.stale,true);assert.equal(stale.rows.get('a').activity.alertEligible,false);
 assert.deepEqual(readFileSync(history),historyBefore);assert.deepEqual(readFileSync(app),appBefore);
 const edit=new DatabaseSync(history);
 edit.exec("INSERT INTO history_identities VALUES(3,'legacy'); INSERT INTO history_allocations VALUES(3,'ref','direct_code','[]','[]')");
 edit.prepare('UPDATE history_references SET master_json=?').run(JSON.stringify([{CIF:'123',PartnerCode:'legacy'}]));
 edit.close();
 buildActivitySnapshot(root,'2026-09-30');
 const incomplete=readActivitySnapshot([{id:'a',cui:'123'}],root,'2026-09-30').rows.get('a');
 assert.equal(incomplete.coverageComplete,false);assert.equal(incomplete.activity.status,'insufficient_history');assert.equal(incomplete.activity.alertEligible,false);
 const revision=new DatabaseSync(history);revision.exec("UPDATE history_meta SET value='other-ref'");revision.close();
 assert.equal(readActivitySnapshot([{id:'a',cui:'123'}],root,'2026-09-30').state,'unavailable','stale allocation snapshot must not be served');
 console.log('PASS: snapshot batch build, read-only sources, access IDs, shared deduplication, cancellation/free movements, incomplete aliases and freshness fences.');
}finally{rmSync(root,{recursive:true,force:true});}
