import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {DatabaseSync} from 'node:sqlite';
import {build} from 'esbuild';
const root=mkdtempSync(join(tmpdir(),'partner-sales-'));
try{
 const bundle=join(root,'store.mjs');
 await build({entryPoints:['lib/partner-sales-store.ts'],outfile:bundle,bundle:true,platform:'node',format:'esm',logLevel:'silent'});
 const {readPartnerSales,PartnerSalesInputError}=await import(pathToFileURL(bundle).href);
 assert.equal(readPartnerSales('p','123',new URLSearchParams(),root).state,'unavailable');
 mkdirSync(join(root,'client-history'));
 const path=join(root,'client-history','client-sales-history.sqlite'),c=new DatabaseSync(path);
 c.exec(`
 CREATE TABLE history_meta(key TEXT,value TEXT);
 INSERT INTO history_meta VALUES('current_reference','ref');
 CREATE TABLE history_references(id TEXT,master_json TEXT);
 INSERT INTO history_references VALUES('ref','[]');
 CREATE TABLE history_imports(id INTEGER,state TEXT,period_start TEXT,period_end TEXT,value_cents INTEGER,quantity_micros INTEGER,row_count INTEGER);
 INSERT INTO history_imports VALUES(1,'active','2026-01-01','2026-09-30',560000,8000000,10);
 CREATE TABLE history_identities(id INTEGER,client_code TEXT);
 INSERT INTO history_identities VALUES(1,'123'),(2,'999');
 CREATE TABLE history_allocations(identity_id INTEGER,reference_id TEXT,status TEXT,partner_ids_json TEXT,candidates_json TEXT);
 INSERT INTO history_allocations VALUES(1,'ref','direct_code','["p1","p2"]','[]'),(2,'ref','direct_code','["other"]','[]');
 CREATE TABLE history_rows(import_id INTEGER,identity_id INTEGER,source_row INTEGER,date TEXT,site_id TEXT,document_number TEXT,value_cents INTEGER,quantity_micros INTEGER,item_code TEXT,item_name TEXT,tr TEXT);
 `);
 const insert=c.prepare('INSERT INTO history_rows VALUES(1,?,?,?,?,?,?,?,\'item\',\'Example product\',\'Original seller\')');
 for(const [i,date] of ['2026-06-01','2026-06-08','2026-06-15','2026-06-22','2026-06-29','2026-07-06'].entries())insert.run(1,i,date,'site',String(i),10000,1000000);
 insert.run(1,7,'2026-09-15','site','cancel',500,1000000);
 insert.run(1,8,'2026-09-15','site','cancel',-500,-1000000);
 insert.run(1,9,'2026-09-25','site','free',0,1000000);
 insert.run(2,10,'2026-09-25','site','other',500000,1000000);
 c.close();
 const before=readFileSync(path);
 const result=readPartnerSales('p1','RO123',new URLSearchParams(),root);
 assert.equal(result.state,'ready');assert.equal(result.totals.rows,9);assert.equal(result.totals.valueCents,60000);
 assert.equal(result.from,'2026-01-01','default summary spans all imported history');
 assert.deepEqual({...result.documents},{count:6,lastBilling:'2026-07-06'});
 assert.equal(result.latestDocuments.length,5);assert.equal(result.latestDocuments[0].document,'5');assert.equal(result.latestDocuments.at(-1).document,'1');
 assert.equal(result.latestDocuments[0].products[0].valueCents,10000);assert.deepEqual(result.latestDocuments[0].sellers,['Original seller']);
 assert.equal(result.activity.lastBilling,'2026-07-06');assert.equal(result.activity.billingDays,6);
 assert.equal(result.sellers[0].seller,'Original seller');assert.equal(result.coverageComplete,true);
 assert.equal(readPartnerSales('p2','123',new URLSearchParams(),root).totals.valueCents,60000,'shared portfolio sees the same facts once');
 assert.equal(readPartnerSales('missing','123',new URLSearchParams(),root).state,'unlinked');
 const month=readPartnerSales('p1','123',new URLSearchParams({from:'2026-07-01',to:'2026-07-31'}),root);
 assert.equal(month.totals.valueCents,10000);assert.equal(month.documents.count,1);assert.equal(month.latestDocuments.length,1);
 const empty=readPartnerSales('p1','123',new URLSearchParams({from:'2025-01-01',to:'2025-12-31'}),root);
 assert.equal(empty.documents.count,0);assert.equal(empty.documents.lastBilling,null);assert.deepEqual(empty.latestDocuments,[]);
 assert.throws(()=>readPartnerSales('p1','123',new URLSearchParams({from:'2026-02-30'}),root),PartnerSalesInputError);
 assert.throws(()=>readPartnerSales('p1','123',new URLSearchParams({page:'-1'}),root),PartnerSalesInputError);
 assert.deepEqual(readFileSync(path),before,'read-only API never modifies history');
 const docs=new DatabaseSync(path);
 docs.exec("UPDATE history_imports SET period_start='2023-01-01'; INSERT INTO history_rows VALUES(1,1,20,'2023-02-01','old-site','5',7000,1000000,'old-item','Old product','Old seller'),(1,1,21,'2026-07-06','site','5',2000,2000000,'item','Example product','Original seller'),(1,1,22,'2026-07-06','other-site','5',3000,1000000,'different','Other product','Other seller'),(1,1,23,'2026-09-28','site','return',-1000,-1000000,'item','Example product','Original seller');");
 docs.close();
 const grouped=readPartnerSales('p1','123',new URLSearchParams(),root);
 assert.equal(grouped.from,'2023-01-01');assert.equal(grouped.totals.valueCents,71000);
 assert.equal(grouped.documents.count,8,'old bill and identical document number at another site remain separate');
 const sameNumber=grouped.latestDocuments.filter(d=>d.date==='2026-07-06'&&d.document==='5');
 assert.equal(sameNumber.length,2);const combined=sameNumber.find(d=>d.site==='site');
 assert.equal(combined.valueCents,12000);assert.equal(combined.products.length,1);assert.equal(combined.products[0].quantityMicros,3000000);
 assert.equal(grouped.latestDocuments.some(d=>d.document==='return'),false,'returns do not become recent positive bills');
 const d=new DatabaseSync(path);
 d.exec("INSERT INTO history_identities VALUES(3,'123'); INSERT INTO history_allocations VALUES(3,'ref','reconcile','[]','[]')");
 d.close();
 const incomplete=readPartnerSales('p1','123',new URLSearchParams(),root);
 assert.equal(incomplete.coverageComplete,false);assert.equal(incomplete.activity.alertEligible,false);
 const aliases=new DatabaseSync(path);
 aliases.exec("DELETE FROM history_identities WHERE id=3; INSERT INTO history_identities VALUES(3,'legacy-code');");
 aliases.prepare('UPDATE history_references SET master_json=?').run(JSON.stringify([{CIF:'123',PartnerCode:'legacy-code'}]));
 aliases.exec("UPDATE history_allocations SET status='direct_code' WHERE identity_id=3");
 aliases.close();
 const aliasIncomplete=readPartnerSales('p1','123',new URLSearchParams(),root);
 assert.equal(aliasIncomplete.coverageComplete,false,'unlinked direct codes and CRM aliases suppress false inactivity');
 console.log('PASS: read-only store, exact partner scope, shared facts, cancellation, zero values, date filters and unresolved-history alerts.');
}finally{rmSync(root,{recursive:true,force:true});}
